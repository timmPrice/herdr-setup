"""Used by tools/fake.sh: rewrite a temp mod copy so "herdr" imports come from fake-herdr.js."""
import json, os, re, sys

root, scen_path, mod, install = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4] == "1"
scen = json.load(open(scen_path))

FAKE = r"""// Generated by tools/fake.sh: the real "herdr" module with scenario data on top.
import * as H from "herdr";
export * from "herdr";
const S = __SCENARIO__;
const AGENT = { address: "t0", pane: "p0", space: "s1", space_name: "fake", tab: "tb1", tab_index: 1, tab_name: "1",
  status: "idle", app: "claude-code", program: { key: "claude", name: "claude", icon: "icons/claude.svg", tint: false, tile: "#d97757", color: "#ffffff", shell: false, agent: true },
  title: "", seq: 0, pinned: false, focused: false };
const PANE = { pane: "p0", terminal: "t0", tab: "tb1", title: "", cwd: "/home/op", branch: null, status: null, app: null,
  program: { key: "shell", name: "zsh", shell: true, agent: false }, focused: false, zoomed: false, movable: true };
const TAB = { id: "tb1", index: 1, name: "1", named: false, active: false, status: null, panes: 1, zoomed: false, settled: false, settled_at: null, changed_at: null, working_since: null };
const SPACE = { id: "s1", index: 1, name: "fake", named: true, folder: "/home/op", machine: null, branch: null, active: false, status: null, tabs: [] };
const fill = (d, x, i) => ({ ...d, seq: i, ...x });
const A = S.agents && S.agents.map((a, i) => fill(AGENT, a, i));
const P = S.panes && S.panes.map((p, i) => fill(PANE, p, i));
const SP = S.spaces && S.spaces.map((s, i) => ({ ...SPACE, index: i + 1, ...s, tabs: (s.tabs ?? []).map((t, j) => ({ ...TAB, index: j + 1, ...t })) }));
export const agents = () => A ?? H.agents();
export const panes = () => P ?? H.panes();
export const spaces = () => SP ?? H.spaces();
export const terminals = () => S.terminals ?? H.terminals();
export const focused = () => ("focused" in S ? S.focused : H.focused());
export const window = () => ("window" in S ? S.window : H.window());
export const props = () => ({ ...(H.props() ?? {}), ...(S.props ?? {}) });
export const shared = (k) => (S.shared && k in S.shared ? S.shared[k] : H.shared(k));
export const setAgentOrder = () => {};
"""

with open(os.path.join(root, "fake-herdr.js"), "w") as f:
    f.write(FAKE.replace("__SCENARIO__", json.dumps(scen, ensure_ascii=False)))

imp = re.compile(r"""(from\s+)(["'])herdr\2""")
for d, _, files in os.walk(root):
    for name in files:
        if not name.endswith(".js") or name == "fake-herdr.js":
            continue
        p = os.path.join(d, name)
        rel = os.path.relpath(os.path.join(root, "fake-herdr.js"), d)
        rel = rel if rel.startswith(".") else "./" + rel
        s = open(p).read()
        s2 = imp.sub(lambda m: f'{m.group(1)}"{rel}"', s)
        if install:  # asset paths follow the installed copy
            s2 = s2.replace(f"mods/{mod}/", f"mods/{mod}-fake/")
        if s2 != s:
            open(p, "w").write(s2)
